// Turns the seeded SQLite file into one SQL file D1 can load.
//
// The seed (scripts/seed.mjs) reads rows back as it goes — it looks up what already exists, keeps
// admin edits, and follows lastInsertRowid between inserts — which is exactly what D1's batch API
// cannot do. Rather than rewrite that logic against an async driver, the seed keeps running against
// a local SQLite file, and this turns the result into plain INSERTs:
//
//   npm run seed -- --demo            # builds data/beed.db as before
//   npm run d1:export                 # writes seed.sql from it
//   npm run d1:load                   # wrangler d1 execute … --file=seed.sql
//
// Rows are written in schema order so a child never lands before its parent.
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dbPath = resolve(root, process.env.BEED_DB ?? 'data/beed.db');
const out = resolve(root, process.argv[2] ?? 'seed.sql');

if (!existsSync(dbPath)) {
  console.error(`No database at ${dbPath}. Run "npm run seed -- --demo" first.`);
  process.exit(1);
}

/** Table names in the order schema.sql creates them: parents before children. */
const schema = readFileSync(resolve(root, 'src/lib/schema.sql'), 'utf8');
const tables = [...schema.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map((m) => m[1]);

const db = new DatabaseSync(dbPath, { readOnly: true });

/** SQLite literal for a value read back from the driver. */
function lit(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (typeof v === 'bigint') return String(v);
  if (v instanceof Uint8Array) return `X'${Buffer.from(v).toString('hex')}'`;
  return `'${String(v).replaceAll("'", "''")}'`;
}

const lines = [
  '-- Generated by scripts/d1-export.mjs from the seeded SQLite file.',
  '-- Load with: npm run d1:load  (add --remote for the deployed database)',
  '',
  // Reloading into a database that already has rows: "DELETE FROM categories" would break products.category_id
  // (D1 always enforces foreign keys) and abort the whole load. Deferred, the keys are checked once at the end,
  // when every table has been refilled with the same ids.
  'PRAGMA defer_foreign_keys = true;',
  '',
];
let total = 0;

for (const table of tables) {
  // Runtime rows, not catalogue: sessions and checkout_nonces belong to one login or one form, and
  // users and audit_log hold whoever signed in on this machine (the developer button creates its
  // user on first use). Staff accounts for a database are made with `admin:password --local|--remote`.
  if (['sessions', 'checkout_nonces', 'users', 'audit_log'].includes(table)) continue;
  const rows = db.prepare(`SELECT * FROM ${table}`).all();
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  lines.push(`DELETE FROM ${table};`);
  for (const r of rows) {
    lines.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => lit(r[c])).join(', ')});`);
    total++;
  }
  lines.push('');
  console.log(`${table}: ${rows.length}`);
}

db.close();
writeFileSync(out, lines.join('\n'));
console.log(`\n${total} rows → ${out}`);
